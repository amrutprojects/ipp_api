import { AppError } from '../../http/errors';
import { contains, offset, pageMeta } from '../../lib/paging';
import {
  FIELD_KIND,
  fieldOptionKind,
  FIXED_KINDS,
  isLinkedKind,
  isProgramKind,
  ORDER_MAX,
  PROGRAM_KINDS,
} from '../../program/constants';
import { loadProgram, optionsKind, optionValue, type ProgramField } from '../../program/masters';
import { lock, orConflict, record, type By } from './common.service';
import type { NewOptionBody, OptionListQuery, UpdateOptionBody } from './options.schemas';

/*
 * The choices of the form's dropdowns, kind by kind (FIELD:<key> = those of a field with choices of its own). A choice that is switched
 * off or deleted is no longer offered; forms that hold it still show its name. A rename never changes what a form stores.
 */
const FIXED_LIST = 'This list is fixed: its entries can be renamed and switched on or off, not added or deleted.';
const duplicateText = (name: string) => `"${name}" is already in this list.`;
const duplicate = (name: string) => AppError.conflict(duplicateText(name));
const duplicates = (name: string) => ({
  uq_program_options_name: duplicateText(name),
  uq_program_options_code: duplicateText(name),
});

const OWN = fieldOptionKind('');
const KIND_RE = new RegExp(`^([A-Z]+(_[A-Z]+)*|${OWN}[a-z][a-z0-9_]{0,49})$`);
/* The prefix of the codes that are generated by number; any other list's code is the choice's name. */
const NUMBERED: Record<string, string> = { CASTE: 'IPP_C', EDUCATION: 'IPP_E', REGION: 'IPP_R', TECHNOLOGY: 'T' };
const CODE_MAX = 120;

/* The form field whose value a choice of this kind is. */
const fieldKeyOf = (kind: string) =>
  kind.startsWith(OWN) ? kind.slice(OWN.length) : Object.keys(FIELD_KIND).find((key) => FIELD_KIND[key] === kind)!;

/* A list of the program, or the choices of a field that has its own; anything else does not exist. */
async function assertKind(db: Db, kind: string): Promise<void> {
  if (!KIND_RE.test(kind)) throw AppError.validation([{ field: 'params.kind', message: 'Unknown list' }]);
  if (isProgramKind(kind)) return;
  const field = kind.startsWith(OWN)
    ? await one<Pick<ProgramField, 'key' | 'type' | 'isCustom'>>(
        `SELECT key, type, is_custom AS "isCustom" FROM program_fields WHERE key = $1 AND deleted_at IS NULL`,
        [fieldKeyOf(kind)],
        db,
      )
    : null;
  if (!field || optionsKind(field) !== kind) throw AppError.notFound('List not found');
}

const lockKind = (db: Db, kind: string) => lock(db, `options:${kind}`);

interface OptionRow {
  id: string;
  kind: string;
  code: string;
  name_en: string;
  name_mr: string | null;
  display_order: number;
  is_active: boolean;
  is_system: boolean;
  in_use: boolean;
}

/*
 * in_use: a form that is not deleted holds the choice (`key` = the parameter with its field's key), also among several
 * (CHECKBOXES). One scan for a page.
 */
const select = (kind: string, key: string) => `SELECT o.id, o.kind, o.code, o.name_en, o.name_mr, o.display_order, o.is_active,
    o.is_system, (${isLinkedKind(kind) ? 'o.id::text' : 'o.code'} IN (
      SELECT c FROM applications p, chosen_values(p.data ->> ${key}::text) c WHERE p.deleted_at IS NULL)) AS in_use
  FROM program_options o`;

const optionDto = (o: OptionRow) => ({
  id: o.id,
  value: optionValue(o),
  code: o.code,
  name_en: o.name_en,
  name_mr: o.name_mr,
  order: o.display_order,
  is_active: o.is_active,
  is_system: o.is_system,
  in_use: o.in_use,
});

async function getOption(db: Db, kind: string, id: string): Promise<OptionRow> {
  const row = await one<OptionRow>(
    `${select(kind, '$3')} WHERE o.kind = $1 AND o.id = $2 AND o.deleted_at IS NULL`,
    [kind, id, fieldKeyOf(kind)],
    db,
  );
  if (!row) throw AppError.notFound('Entry not found in this list');
  return row;
}

const hasName = (db: Db, kind: string, nameEn: string) =>
  one(`SELECT 1 FROM program_options WHERE kind = $1 AND lower(name_en) = lower($2) AND deleted_at IS NULL`, [kind, nameEn], db);

/* The next number of a list's generated codes; a deleted one's is never given again. */
async function nextNumber(db: Db, kind: string, prefix: string): Promise<number> {
  const row = await one<{ n: number }>(
    `SELECT coalesce(max(substr(code, $2)::int), 0) + 1 AS n FROM program_options WHERE kind = $1 AND code ~ $3`,
    [kind, prefix.length + 1, `^${prefix}[0-9]{1,6}$`],
    db,
  );
  return row!.n;
}

/* The code a new choice stores in a form: its number, the scale's number, or its name (unique in the list). */
async function newCode(db: Db, kind: string, nameEn: string): Promise<string> {
  const prefix = NUMBERED[kind];
  if (prefix) return `${prefix}${String(await nextNumber(db, kind, prefix)).padStart(kind === 'TECHNOLOGY' ? 2 : 1, '0')}`;
  const taken = (code: string) =>
    one(`SELECT 1 FROM program_options WHERE kind = $1 AND lower(code) = lower($2) AND deleted_at IS NULL`, [kind, code], db);
  if (kind === 'CGPA_SCALE') {
    const scale = String(Number(nameEn));
    if (await taken(scale)) throw duplicate(scale);
    return scale;
  }
  /* The whole name when it fits; never half a character. */
  const cut = (max: number) => [...nameEn].slice(0, max).join('').trim();
  let code = cut(CODE_MAX);
  for (let n = 2; await taken(code); n++) code = `${cut(CODE_MAX - ` (${n})`.length)} (${n})`;
  return code;
}

interface SameName {
  id: string;
  name_en: string;
  name_mr: string | null;
  deleted: boolean;
}

/*
 * The row of a caste, education or region that already has this name. A form stores its id, so one that was deleted is
 * brought back rather than made again: old and new forms hold the same value. A caste's own name is the Marathi one; given
 * only in English, it is also found by its English name.
 */
const sameLinkedRow = (db: Db, kind: string, name: string, byEnglish: boolean) => {
  const own = kind === 'CASTE' ? 'coalesce(name_mr, name_en)' : 'name_en';
  return one<SameName>(
    `SELECT id, name_en, name_mr, (deleted_at IS NOT NULL) AS deleted FROM program_options
     WHERE kind = $1 AND (lower(${own}) = lower($2) OR ($3::boolean AND lower(name_en) = lower($2)))
     ORDER BY (deleted_at IS NOT NULL), (lower(${own}) = lower($2)) DESC, deleted_at DESC LIMIT 1`,
    [kind, name, byEnglish],
    db,
  );
};

/* The end of a list. */
const END = `(SELECT least(coalesce(max(display_order), 0) + 10, ${ORDER_MAX}) FROM program_options WHERE kind = $1::varchar AND deleted_at IS NULL)`;

/* A new choice at the end of its list (or at `order`). The kind's lock is held by the caller. */
async function insertOption(db: Db, kind: string, body: NewOptionBody): Promise<OptionRow> {
  if (await hasName(db, kind, body.name_en)) throw duplicate(body.name_en);
  const given = body.name_mr ?? null;
  if (isLinkedKind(kind)) {
    const name = kind === 'CASTE' ? (given ?? body.name_en) : body.name_en;
    const same = await sameLinkedRow(db, kind, name, kind === 'CASTE' && !given);
    if (same && !same.deleted) throw AppError.conflict(`"${name}" is already in this list as "${same.name_en}".`);
    if (same) {
      await db.query(
        `UPDATE program_options SET name_en = $3, name_mr = $4, display_order = coalesce($5, ${END}), is_active = $6, deleted_at = NULL
         WHERE kind = $1 AND id = $2`,
        [
          kind,
          same.id,
          body.name_en,
          given ?? (kind === 'CASTE' ? same.name_mr : null),
          body.order ?? null,
          body.is_active ?? true,
        ],
      );
      return getOption(db, kind, same.id);
    }
  }
  const row = await one<{ id: string }>(
    `INSERT INTO program_options (kind, code, name_en, name_mr, display_order, is_active)
     VALUES ($1::varchar, $2, $3, $4, coalesce($5, ${END}), $6) RETURNING id`,
    [kind, await newCode(db, kind, body.name_en), body.name_en, given, body.order ?? null, body.is_active ?? true],
    db,
  );
  return getOption(db, kind, row!.id);
}

/* Adds the choices the list of a field with choices of its own does not have yet. */
export async function addChoices(db: Db, fieldKey: string, choices: NewOptionBody[]): Promise<void> {
  const kind = fieldOptionKind(fieldKey);
  await lockKind(db, kind);
  for (const choice of choices) if (!(await hasName(db, kind, choice.name_en))) await insertOption(db, kind, choice);
}

export const optionsService = {
  /* The program's lists, with how many entries each has. The choices of a field that has its own are edited from the field. */
  async kinds() {
    const program = await loadProgram();
    return PROGRAM_KINDS.map((kind) => {
      const all = program.allOf(kind);
      const fixed = FIXED_KINDS.includes(kind);
      return {
        kind,
        name: program.label(fieldKeyOf(kind)),
        count: all.length,
        active: all.filter((o) => o.isActive).length,
        can_add: !fixed,
        can_delete: !fixed,
        stored_as: isLinkedKind(kind) ? ('master' as const) : ('code' as const),
      };
    });
  },

  async list(kind: string, q: OptionListQuery) {
    await assertKind(pool, kind);
    const params: unknown[] = [kind];
    let where = 'o.kind = $1 AND o.deleted_at IS NULL';
    if (q.status) where += ` AND o.is_active = ${q.status === 'ACTIVE'}`;
    if (q.search) {
      const n = `$${params.push(contains(q.search))}`;
      where += ` AND (o.name_en ILIKE ${n} OR o.name_mr ILIKE ${n} OR o.code ILIKE ${n})`;
    }
    const total = (await one<{ n: number }>(`SELECT count(*) AS n FROM program_options o WHERE ${where}`, params))!.n;
    const key = `$${params.push(fieldKeyOf(kind))}`;
    const sort = q.sortBy === 'name' ? 'lower(o.name_en)' : 'o.display_order';
    const items = await rows<OptionRow>(
      `${select(kind, key)} WHERE ${where} ORDER BY ${sort} ${q.sortOrder}, lower(o.name_en), o.id
       LIMIT $${params.push(q.limit)} OFFSET $${params.push(offset(q))}`,
      params,
    );
    return { items: items.map(optionDto), meta: pageMeta(q, total) };
  },

  create(who: By, kind: string, body: NewOptionBody) {
    return orConflict(duplicates(body.name_en), () =>
      transaction(async (db) => {
        await assertKind(db, kind);
        if (FIXED_KINDS.includes(kind)) throw AppError.conflict(FIXED_LIST);
        if (kind === 'CGPA_SCALE' && !/^([1-9]\d?|100)$/.test(body.name_en))
          throw AppError.validation([{ field: 'body.name_en', message: 'Enter the scale as a whole number from 1 to 100' }]);
        await lockKind(db, kind);
        const row = await insertOption(db, kind, body);
        await record(db, who, 'edp.master.create', 'program_options', row.id, { kind });
        return optionDto(row);
      }),
    );
  },

  update(who: By, kind: string, id: string, body: UpdateOptionBody) {
    return orConflict(duplicates(body.name_en ?? ''), () =>
      transaction(async (db) => {
        await assertKind(db, kind);
        await lockKind(db, kind);
        const before = await getOption(db, kind, id);
        await db.query(
          `UPDATE program_options SET name_en = $2, name_mr = $3, display_order = $4, is_active = $5 WHERE id = $1`,
          [
            id,
            body.name_en ?? before.name_en,
            body.name_mr === undefined ? before.name_mr : body.name_mr,
            body.order ?? before.display_order,
            body.is_active ?? before.is_active,
          ],
        );
        await record(db, who, 'edp.master.update', 'program_options', id, { kind, fields: Object.keys(body) });
        return optionDto(await getOption(db, kind, id));
      }),
    );
  },

  /* Deleted: no longer offered; forms that hold it still show its name. */
  remove(who: By, kind: string, id: string) {
    return transaction(async (db) => {
      await assertKind(db, kind);
      await lockKind(db, kind);
      const row = await getOption(db, kind, id);
      if (row.is_system) throw AppError.conflict(FIXED_LIST);
      await db.query('UPDATE program_options SET deleted_at = now(), is_active = false WHERE id = $1', [id]);
      await record(db, who, 'edp.master.delete', 'program_options', id, { kind, in_use: row.in_use });
    });
  },
};
